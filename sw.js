/* ================================================================== */
/* ==================== SERVICE WORKER (app shell) =================== */
/* ================================================================== */
/* Scope is deliberately narrow: this only caches the STATIC APP SHELL
   (index.html, the local js/*.js and views/*.js files, css/*.css, and
   the icons) — enough for the app to finish loading and show its UI
   when opened with no connection, plus a real "add to home screen"
   PWA install prompt now that manifest.json exists.

   What this explicitly does NOT do, and why:
   - Does not cache or intercept ANY Firebase Realtime Database traffic
     (*.firebaseio.com, *.firebasedatabase.app) or the Firebase Auth /
     Cloud Functions / Gemini endpoints. This app's entire reason for
     being is showing live, current student/finance/attendance data —
     silently serving a cached snapshot of that from a service worker
     would be actively wrong, not just imperfect. The fetch handler
     below explicitly passes those requests straight through to the
     network with no caching involved.
   - Does not cache the third-party CDN scripts (Tailwind, Firebase SDK,
     Chart.js, etc). Same reasoning as scripts/build-sw-precache.mjs:
     silently pinning a security-relevant library forever in the SW
     cache is worse than just letting the browser's normal HTTP cache
     (with the CDN's own real cache headers) handle them.
   - Does not attempt background sync for offline-taken actions
     (attendance marks, payments entered with no connection). That's a
     meaningfully bigger feature — queuing writes and replaying them
     against Firebase once back online, with real conflict handling —
     tracked separately, not something to bolt on inside a caching
     layer. Right now, if you're offline: the app SHELL loads (so you
     at least see the UI and any status the app itself shows, like
     `js/error-handler.js`'s toast on a failed write), but any actual
     read/write to Firebase still needs a live connection.

   Cache versioning: CACHE_NAME below is generated by
   scripts/build-sw-precache.mjs from a content hash of everything it
   precaches — so any code change automatically gets a new cache name
   next deploy, and the activate handler below deletes old ones. No
   manual "remember to bump the version number" step. */

const MANIFEST_URL = 'sw-precache-manifest.json';
const CACHE_PREFIX = 'meram-shell-v';

// Hosts that must NEVER be served from cache — always network. Kept as
// an explicit allowlist-style check (rather than "cache everything
// except what's in the precache list") so a same-origin path we didn't
// anticipate still defaults to network-first behavior below, rather
// than silently being cached by accident.
const NEVER_CACHE_HOST_PATTERNS = [
  /\.firebaseio\.com$/,
  /\.firebasedatabase\.app$/,
  /^firestore\.googleapis\.com$/,
  /^identitytoolkit\.googleapis\.com$/,
  /^securetoken\.googleapis\.com$/,
  /\.cloudfunctions\.net$/,
  /^generativelanguage\.googleapis\.com$/,
  /^www\.googleapis\.com$/,
];

function isNeverCacheRequest(url) {
  try {
    const u = new URL(url);
    return NEVER_CACHE_HOST_PATTERNS.some((re) => re.test(u.hostname));
  } catch {
    return false;
  }
}

let cacheNamePromise = null;
async function getCacheName() {
  if (cacheNamePromise) return cacheNamePromise;
  cacheNamePromise = (async () => {
    try {
      const res = await fetch(MANIFEST_URL, { cache: 'no-store' });
      const manifest = await res.json();
      return CACHE_PREFIX + (manifest.version || 'unknown');
    } catch (err) {
      // If the manifest itself can't be fetched (e.g. very first
      // install with a flaky connection), fall back to a fixed name
      // rather than failing installation outright — worst case, the
      // next successful activate cleans it up once the manifest is
      // reachable.
      console.warn('[sw] could not load precache manifest, using fallback cache name', err);
      return CACHE_PREFIX + 'fallback';
    }
  })();
  return cacheNamePromise;
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    try {
      const res = await fetch(MANIFEST_URL, { cache: 'no-store' });
      const manifest = await res.json();
      const cacheName = CACHE_PREFIX + (manifest.version || 'unknown');
      const cache = await caches.open(cacheName);
      // addAll fails the whole install if ANY single file 404s — for an
      // app shell that's the right behavior (a half-cached shell is
      // worse than no offline support at all), but log which file it
      // was so it's diagnosable rather than a bare rejected promise.
      await cache.addAll(manifest.files);
    } catch (err) {
      console.error('[sw] install/precache failed — offline shell will not be available this deploy', err);
      // Deliberately not re-throwing: a failed precache shouldn't brick
      // the app for online use, it just means no offline fallback yet.
    }
  })());
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cacheName = await getCacheName();
    const keys = await caches.keys();
    await Promise.all(
      keys
        .filter((k) => k.startsWith(CACHE_PREFIX) && k !== cacheName)
        .map((k) => caches.delete(k))
    );
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return; // never intercept writes

  if (isNeverCacheRequest(req.url)) return; // let Firebase/Gemini/etc go straight to network, untouched

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // any other cross-origin request (CDN scripts) — normal browser handling, not ours to cache

  event.respondWith((async () => {
    const cacheName = await getCacheName();
    const cache = await caches.open(cacheName);
    const cached = await cache.match(req);

    // Stale-while-revalidate for the app shell: serve the cached copy
    // immediately if we have one (fast, works offline), but still fetch
    // a fresh copy in the background and update the cache for next
    // time. A hard app reload is what actually picks up the new
    // version's JS (browsers don't hot-swap already-executing scripts),
    // but this at least means the NEXT load already has the update
    // ready rather than fetching it live.
    const networkFetch = fetch(req).then((res) => {
      if (res && res.ok) cache.put(req, res.clone());
      return res;
    }).catch(() => null);

    if (cached) return cached;
    const network = await networkFetch;
    if (network) return network;
    // Both cache and network failed (offline + not precached, e.g. a
    // brand-new file added after the SW's last activate) — for a
    // navigation request, fall back to the cached index.html shell
    // rather than showing the browser's own offline error page.
    if (req.mode === 'navigate') {
      const shell = await cache.match('index.html');
      if (shell) return shell;
    }
    return new Response('Oflayn və keş yoxdur (bu fayl hələ keşlənməyib).', { status: 503, statusText: 'Offline' });
  })());
});
